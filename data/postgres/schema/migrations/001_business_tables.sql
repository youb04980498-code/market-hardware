CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS orders;
CREATE SCHEMA IF NOT EXISTS inventory;
CREATE SCHEMA IF NOT EXISTS payments;
CREATE SCHEMA IF NOT EXISTS monitoring;

CREATE TABLE auth.users (
 user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username text NOT NULL UNIQUE CHECK (btrim(username) <> ''),
 password_hash text NOT NULL,
 is_active boolean NOT NULL DEFAULT false,
 customer_id bigint CHECK (customer_id > 0), -- Logical reference; no cross-service FK.
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK ((password_hash LIKE '$argon2%' OR password_hash LIKE '$2%')
        OR (NOT is_active AND password_hash LIKE '!disabled%'))
);
CREATE TABLE auth.roles (
 role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE CHECK (name IN ('customer','operator','admin'))
);
CREATE TABLE auth.user_roles (
 user_id bigint REFERENCES auth.users(user_id) ON DELETE RESTRICT,
 role_id bigint REFERENCES auth.roles(role_id) ON DELETE RESTRICT,
 PRIMARY KEY (user_id,role_id)
);
CREATE INDEX user_roles_role_idx ON auth.user_roles(role_id);

CREATE TABLE orders.customers (
 customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name text NOT NULL, last_name text NOT NULL,
 email text NOT NULL UNIQUE CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE orders.orders (
 order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id bigint NOT NULL REFERENCES orders.customers(customer_id) ON DELETE RESTRICT,
 status text NOT NULL CHECK (status IN ('PENDING','STOCK_RESERVED','PAID','PAYMENT_FAILED','CANCELLED','SHIPPED','DELIVERED','REFUNDED')),
 total_cents bigint NOT NULL CHECK (total_cents >= 0),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_idx ON orders.orders(customer_id);
CREATE INDEX orders_status_time_idx ON orders.orders(status,created_at);
CREATE TABLE orders.order_items (
 order_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES orders.orders(order_id) ON DELETE RESTRICT,
 product_id bigint NOT NULL CHECK (product_id > 0),
 quantity integer NOT NULL CHECK (quantity > 0),
 unit_price_cents bigint NOT NULL CHECK (unit_price_cents >= 0),
 UNIQUE (order_id,product_id)
);
CREATE INDEX order_items_product_idx ON orders.order_items(product_id);

CREATE TABLE inventory.warehouses (
 warehouse_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE, city text NOT NULL,
 capacity_units integer NOT NULL CHECK (capacity_units >= 0)
);
CREATE TABLE inventory.stock (
 product_id bigint NOT NULL CHECK (product_id > 0),
 warehouse_id bigint NOT NULL REFERENCES inventory.warehouses(warehouse_id) ON DELETE RESTRICT,
 quantity integer NOT NULL CHECK (quantity >= 0),
 reserved_quantity integer NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0 AND reserved_quantity <= quantity),
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (product_id,warehouse_id)
);
CREATE INDEX stock_warehouse_idx ON inventory.stock(warehouse_id);
CREATE TABLE inventory.reservations (
 reservation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL CHECK (order_id > 0),
 product_id bigint NOT NULL, warehouse_id bigint NOT NULL,
 quantity integer NOT NULL CHECK (quantity > 0),
 status text NOT NULL CHECK (status IN ('ACTIVE','RELEASED','COMMITTED')),
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY (product_id,warehouse_id) REFERENCES inventory.stock(product_id,warehouse_id) ON DELETE RESTRICT,
 UNIQUE (order_id,product_id,warehouse_id)
);
CREATE INDEX reservations_stock_idx ON inventory.reservations(product_id,warehouse_id,status);

CREATE TABLE payments.payments (
 payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL CHECK (order_id > 0),
 amount_cents bigint NOT NULL CHECK (amount_cents >= 0),
 status text NOT NULL CHECK (status IN ('PENDING','SUCCEEDED','FAILED','REFUNDED')),
 method text NOT NULL CHECK (method = 'SIMULATED_CARD'),
 idempotency_key text NOT NULL UNIQUE CHECK (btrim(idempotency_key) <> ''),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX payments_order_idx ON payments.payments(order_id);
CREATE INDEX payments_status_time_idx ON payments.payments(status,created_at);
CREATE TABLE payments.invoices (
 invoice_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL CHECK (order_id > 0),
 payment_id bigint NOT NULL UNIQUE REFERENCES payments.payments(payment_id) ON DELETE RESTRICT,
 invoice_number text NOT NULL UNIQUE,
 issued_at timestamptz NOT NULL,
 total_cents bigint NOT NULL CHECK (total_cents >= 0),
 pdf_object_key text NOT NULL CHECK (btrim(pdf_object_key) <> ''),
 status text NOT NULL CHECK (status IN ('PENDING','ISSUED','VOID'))
);
CREATE INDEX invoices_order_idx ON payments.invoices(order_id);
CREATE TABLE payments.notification_deliveries (
 delivery_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_id bigint NOT NULL REFERENCES payments.invoices(invoice_id) ON DELETE RESTRICT,
 recipient text NOT NULL,
 status text NOT NULL CHECK (status IN ('PENDING','SENT','FAILED')),
 attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
 last_error text, sent_at timestamptz,
 UNIQUE (invoice_id,recipient),
 CHECK (status <> 'SENT' OR (sent_at IS NOT NULL AND attempts > 0))
);

