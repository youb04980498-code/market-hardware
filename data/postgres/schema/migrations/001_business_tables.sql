CREATE TABLE monitoring.application_logs (
 log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(), service_name text NOT NULL,
 level text NOT NULL CHECK (level IN ('DEBUG','INFO','WARNING','WARN','ERROR','CRITICAL')),
 request_id text, trace_id text, method text, path text,
 status_code integer CHECK (status_code BETWEEN 100 AND 599),
 duration_ms numeric CHECK (duration_ms >= 0), message text NOT NULL,
 metadata_json jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(metadata_json) = 'object')
);
CREATE INDEX logs_created_idx ON monitoring.application_logs(created_at);
CREATE INDEX logs_service_idx ON monitoring.application_logs(service_name,created_at);
CREATE INDEX logs_trace_idx ON monitoring.application_logs(trace_id);
CREATE TABLE monitoring.business_audit (
 audit_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 occurred_at timestamptz NOT NULL DEFAULT now(), table_name text NOT NULL,
 operation text NOT NULL, record_id text NOT NULL,
 old_status text, new_status text, transaction_id bigint NOT NULL
);
